const fs=require('node:fs'),assert=require('node:assert/strict');
const raw=require('./week-8-results.json'),data=require('../team-performance-data.js'),awards=require('../season-awards-data.js'),swami=require('./swami-picks.json');
const week=swami.weeks.find(w=>w.week===8),picks=swami.weeks.flatMap(w=>w.picks);
assert.equal(week.picks.filter(p=>p.pick===p.winner).length,3);
assert.ok(week.picks.every(p=>p.winner&&p.scores&&p.recap&&p.source));
assert.equal(picks.filter(p=>p.pick===p.winner).length,21);
assert.equal(picks.filter(p=>p.winner&&p.winner!=='tie'&&p.winner!==p.pick).length,15);
assert.equal(picks.filter(p=>p.winner===null).length,0);
assert.deepEqual(week.picks.map(p=>p.winner),['Silence of the Lamb','Dillon’s Team','Chris’s Team','Daniel’s Primo Team','Mark’s Team','Slim Pickens']);
assert.equal(data.week,8);
const rows=require('../team-performance.js').calculateTeamPerformance(data,awards);
assert.equal(rows.length,12);
assert.equal(awards.weeks.filter(w=>w.complete).length,8);
assert.equal(rows.find(r=>r.id==='dan-e').possible,203.76);
assert.equal(rows.find(r=>r.id==='brett-d').possible,106.34);
assert.equal(rows.find(r=>r.id==='dusty-d').possible,132.82);
assert.equal(rows.find(r=>r.id==='mark-ma').missed,0);
assert.equal(Math.max(...rows.map(r=>r.actual)),170.98);
assert.equal(Math.min(...raw.matchups.map(m=>Math.round(Math.abs(m.scores[0]-m.scores[1])*100))),432);
const underdogs=raw.matchups.map(m=>({m,i:m.scores[0]>m.scores[1]?0:1})).filter(({m,i})=>m.originalProjections[i]<m.originalProjections[1-i]).sort((a,b)=>(b.m.originalProjections[1-b.i]-b.m.originalProjections[b.i])-(a.m.originalProjections[1-a.i]-a.m.originalProjections[a.i]));
assert.equal(underdogs.length,2);assert.deepEqual(underdogs[0].m.ids,[3,9]);
const swaps=[];
for(const t of data.teams)for(const b of t.players.slice(9))for(let i=0;i<9;i++)if(data.slots[i]==='W/R/T'?['WR','RB','TE'].includes(b[1]):b[1]===data.slots[i])swaps.push({team:t.id,bench:b[0],starter:t.players[i][0],gain:Math.round((b[2]-t.players[i][2])*100)});
assert.deepEqual(swaps.sort((a,b)=>b.gain-a.gain)[0],{team:'dan-e',bench:'Tyler Allgeier',starter:'Aaron Jones Sr.',gain:3310});
const allPlay=require('./all-play-records.cjs').calculateAllPlay(awards,data.teams);
assert.equal(allPlay.weeks.length,8);
assert.ok(allPlay.rows.every(t=>t.wins+t.losses+t.ties===88));
for(const file of ['weekly-updates.html','matchup.html']){
 const html=fs.readFileSync(file,'utf8'),ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
 assert.equal(new Set(ids).size,ids.length,'Duplicate ID in '+file);
 assert.ok(html.includes('21–15'));assert.equal(fs.readFileSync('dist/'+file,'utf8'),html);
}
const weekly=fs.readFileSync('weekly-updates.html','utf8');
assert.ok(weekly.includes('Week 8 Highlights'));assert.ok(weekly.includes('scope="colgroup" colspan="8"'));
for(let n=1;n<=7;n++)assert.ok(weekly.includes('Week '+n+' recap archive'));
assert.ok(weekly.includes('href="#week-8-results-heading"'));
const matchup=fs.readFileSync('matchup.html','utf8');
assert.ok(matchup.includes('WEEK 8 FEATURED MATCHUP • FINAL RESULT'));
assert.ok(matchup.includes('Original Prediction'));assert.ok(matchup.includes('The Final Word'));
console.log('Week 8 results verified: six grades, Swami 3–3 / season 21–15, 12 valid lineups, highlight calculations, eight-week tables, and preserved archives.');
