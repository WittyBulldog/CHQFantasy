const fs=require('node:fs'),path=require('node:path');
const current=require('../team-performance-data.js');
const awards=require('../season-awards-data.js');
const {calculateTeamPerformance}=require('../team-performance.js');
// Archive a completed roster as team-performance-week-N.js before replacing
// the current roster. The selector discovers archived weeks at build time.
const byWeek=new Map();
for(const file of fs.readdirSync(__dirname).filter(f=>/^team-performance-week-\d+\.js$/.test(f))){
  const data=require(path.join(__dirname,file));
  if(data.season===current.season) byWeek.set(data.week,data);
}
byWeek.set(current.week,current);
const weeks=awards.weeks.filter(w=>w.complete).map(w=>{
  const data=byWeek.get(w.week);
  if(!data) throw Error('Missing archived performance roster for Week '+w.week);
  calculateTeamPerformance(data,awards);
  return data;
}).sort((a,b)=>a.week-b.week);
fs.writeFileSync(path.join(__dirname,'../team-performance-history.js'),'// Generated by data/build-performance-history.cjs\nconst CHQ_TEAM_PERFORMANCE_WEEKS = '+JSON.stringify(weeks)+';\n');
