const assert=require('node:assert/strict'),fs=require('node:fs');
const raw=require('./week-7-results.json'),data=require('../team-performance-data.js'),awards=require('../season-awards-data.js');
const swami=require('./swami-picks.json');
const rows=require('../team-performance.js').calculateTeamPerformance(data,awards);
assert.equal(data.week,7);assert.equal(rows.length,12);
assert.equal(new Set(raw.matchups.flatMap(m=>m.ids)).size,12);
assert.equal(awards.weeks.filter(w=>w.complete).length,7);
assert.equal(rows.find(r=>r.id==='dan-e').actual,169.34);
assert.equal(rows.find(r=>r.id==='mickey-b').possible,106.22);
assert.equal(rows.find(r=>r.id==='mark-me').possible,123.68);
for(const id of ['brett-d','dillon-m','jason-b'])assert.equal(rows.find(r=>r.id===id).missed,0);
assert.equal(Math.min(...raw.matchups.map(m=>Math.round(Math.abs(m.scores[0]-m.scores[1])*100))),90);
const underdogs=raw.matchups.filter(m=>{const i=m.scores[0]>m.scores[1]?0:1;return m.originalProjections[i]<m.originalProjections[1-i];});
assert.equal(underdogs.length,1);assert.deepEqual(underdogs[0].ids,[9,12]);
const swaps=[];
for(const t of data.teams)for(const bench of t.players.slice(9))for(let i=0;i<9;i++)if(data.slots[i]==='W/R/T'?['WR','RB','TE'].includes(bench[1]):bench[1]===data.slots[i])swaps.push({team:t.id,name:bench[0],starter:t.players[i][0],gain:Math.round((bench[2]-t.players[i][2])*100)});
assert.deepEqual(swaps.sort((a,b)=>b.gain-a.gain)[0],{team:'mickey-b',name:'Omar Cooper Jr.',starter:'Jalen Coker',gain:2360});
assert.ok(!swami.weeks.some(w=>w.week===7&&w.picks.length),'No retroactive Week 7 predictions');
const picks=swami.weeks.flatMap(w=>w.picks);
assert.equal(picks.filter(p=>p.winner===p.pick).length,18);
assert.equal(picks.filter(p=>p.winner&&p.winner!=='tie'&&p.winner!==p.pick).length,12);
const html=fs.readFileSync('weekly-updates.html','utf8');
assert.ok(html.includes('Week 7 Highlights'));assert.ok(html.includes('No Week 7 picks were submitted'));
assert.ok(html.includes('18–12 (60.0%)'));
assert.ok(html.includes('href="#week-7-results-heading"'));
for(let week=1;week<=6;week++)assert.ok(html.includes(`Week ${week} recap archive`));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'No duplicate archive or jump targets');
assert.ok(html.includes('scope="colgroup" colspan="7"'));
assert.ok(html.includes('team-performance-history.js?v='));
assert.equal(fs.readFileSync('dist/weekly-updates.html','utf8'),html);
console.log('Week 7 verified: six results, all 12 lineups, closest margin, only upset, biggest bench swap, seven-week tables, archive links, and unchanged Swami record.');
