const fs=require('node:fs'),assert=require('node:assert/strict');
const data=require('./swami-picks.json'),week=data.weeks.find(w=>w.week===8);
assert.equal(week.picks.length,6);
assert.equal(new Set(week.picks.flatMap(p=>p.teams)).size,12);
assert.deepEqual(week.picks.map(p=>p.pick),['Silence of the Lamb','Dillon’s Team','Mels-16','Gotham Knights','West Coast','Slim Pickens']);
assert.ok(week.picks.every(p=>p.winner===null&&!p.scores&&!p.recap));
assert.deepEqual(week.picks.find(p=>p.featured).teams,['Silence of the Lamb','DonkeyWoodDean']);
assert.equal(week.picks.filter(p=>p.lock).length,1);
assert.equal(week.picks.find(p=>p.lock).pick,'West Coast');
const all=data.weeks.flatMap(w=>w.picks);
assert.equal(all.filter(p=>p.winner===p.pick).length,18);
assert.equal(all.filter(p=>p.winner&&p.winner!=='tie'&&p.winner!==p.pick).length,12);
assert.equal(all.filter(p=>p.winner===null).length,6);
assert.ok(!data.weeks.some(w=>w.week===7&&w.picks.length));
const html=fs.readFileSync('matchup.html','utf8');
assert.ok(html.includes('WEEKLY FEATURE • WEEK 8 PICKS'));
assert.ok(html.includes('WEEK 8 FEATURED MATCHUP'));
assert.ok(html.includes('Week 6 featured matchup archive'));
assert.ok(html.includes('Lock of the week • Pending'));
assert.ok(html.includes('Week 7 had no submitted picks'));
assert.ok(html.includes('Week 8 predictions &amp; results'));
const feature=html.match(/<!-- MATCHUP FEATURE:START -->([\s\S]*?)<!-- MATCHUP FEATURE:END -->/)[1];
assert.ok(feature.includes('PREDICTED WINNER'));
assert.ok(!feature.includes('FINAL RESULT'));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size);
assert.equal(fs.readFileSync('dist/matchup.html','utf8'),html);
console.log('Week 8 picks verified: six pending predictions, featured matchup, lock, unchanged season record, no Week 7 grading, and preserved archives.');
