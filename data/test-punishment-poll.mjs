import assert from 'node:assert/strict';
import fs from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import {createHash} from 'node:crypto';
import {snapshot,publicSnapshot,castVote,changePhase,advance,selectWinners} from '../poll-api/src/core.mjs';
import worker from '../poll-api/src/index.mjs';
import {ENTRIES,INITIAL_MATCHES} from '../punishment-poll-data.mjs';

function database(){
 const sql=new DatabaseSync(':memory:');sql.exec('PRAGMA foreign_keys=ON;');sql.exec(fs.readFileSync('poll-api/migrations/0001_poll.sql','utf8'));
 const prepare=text=>{let args=[];const statement=()=>sql.prepare(text);const handle={bind(...values){args=values;return handle;},async first(){return statement().get(...args)||null;},async all(){return {results:statement().all(...args)};},async run(){const result=statement().run(...args);return {meta:{changes:Number(result.changes)}};}};return handle;};
 return {prepare,async batch(statements){sql.exec('BEGIN');try{const results=[];for(const s of statements)results.push(await s.run());sql.exec('COMMIT');return results;}catch(e){sql.exec('ROLLBACK');throw e;}},close(){sql.close();}};
}
const db=database();
assert.equal(new Set(ENTRIES.map(e=>e.id)).size,8);
assert.deepEqual((await snapshot(db)).matches.map(m=>({id:m.id,round:m.round,left:m.left,right:m.right})),INITIAL_MATCHES);
assert.equal(await castVote(db,'owner1','qf1','calendar'),false,'Draft votes must fail');
assert.equal(await changePhase(db,'open',0),true);
assert.equal(await castVote(db,'owner1','qf1','unknown'),false);
assert.equal(await castVote(db,'owner1','qf1','calendar'),true);
assert.equal(await castVote(db,'owner1','qf1','bowling'),true);
let state=await snapshot(db,'owner1');
assert.equal(state.matches[0].myVote,'bowling');
assert.deepEqual(state.matches[0].counts,{bowling:1},'Changing a vote must not add a second ballot');
assert.equal(publicSnapshot(state).matches[0].counts,null);
assert.equal(publicSnapshot(state).matches[0].total,1);
assert.equal(await castVote(db,'owner2','qf1','calendar'),true);
assert.equal(await castVote(db,'owner1','qf2','5k'),true);
assert.equal(await castVote(db,'owner1','qf3','pancakes'),true);
assert.equal(await changePhase(db,'close',1),true);
assert.equal(await castVote(db,'owner1','qf2','dinner'),false,'Votes after close must fail');
state=await snapshot(db);
assert.deepEqual(publicSnapshot(state).matches[0].counts,{bowling:1,calendar:1});
await assert.rejects(advance(db,state,{}),/tied/);
await assert.rejects(advance(db,state,{qf1:'calendar'}),/at least one vote/);
assert.equal(await changePhase(db,'reopen',2),true);
assert.equal(await castVote(db,'owner1','qf4','plunge'),true);
assert.equal(await changePhase(db,'close',3),true);
state=await snapshot(db);
await assert.rejects(advance(db,state,{qf1:'calendar',qf2:'5k'}),/Only tied/);
assert.equal(await advance(db,state,{qf1:'calendar'}),true);
assert.equal(await advance(db,state,{qf1:'calendar'}),false,'Stale advance must not duplicate matches');
let next=await snapshot(db);
assert.equal(next.round,2);assert.equal(next.phase,'open');
assert.deepEqual(next.matches.filter(m=>m.round===2).map(m=>[m.left,m.right]),[['calendar','5k'],['pancakes','plunge']]);
assert.equal(await castVote(db,'owner1','qf1','bowling'),false,'Past-round votes must fail');
assert.equal(await castVote(db,'owner1','sf1','calendar'),true);
assert.equal(await castVote(db,'owner1','sf2','plunge'),true);
assert.equal(await changePhase(db,'close',next.revision),true);
assert.equal(await advance(db,await snapshot(db),{}),true);
next=await snapshot(db);assert.equal(next.round,3);
assert.equal(await castVote(db,'owner1','final','plunge'),true);
assert.equal(await changePhase(db,'close',next.revision),true);
assert.equal(await advance(db,await snapshot(db),{}),true);
next=await snapshot(db);assert.equal(next.phase,'complete');
assert.equal(next.matches.find(m=>m.id==='final').winner,'plunge');
assert.equal(await castVote(db,'owner2','final','calendar'),false);
assert.throws(()=>selectWinners([{id:'x',left:'a',right:'b',counts:{a:1,b:1}}],{x:'c'}),/tied/);
db.close();

