const assert=require('node:assert/strict'),fs=require('node:fs');
const swami=require('./swami-picks.json');
const week=swami.weeks.find(w=>w.week===3);
assert.equal(week.picks.filter(p=>p.pick===p.winner).length,4);
assert.ok(week.picks.every(p=>p.winner && p.scores && p.recap));
const all=swami.weeks.flatMap(w=>w.picks);
assert.equal(all.filter(p=>p.winner===p.pick).length,8);
const awards=require('../season-awards-data.js');
const data=require('../team-performance-data.js');
const rows=require('../team-performance.js').calculateTeamPerformance(data,awards);
assert.equal(data.week,3);
assert.equal(rows.length,12);
assert.equal(rows.find(r=>r.id==='brett-d').possible,200.40);
assert.equal(rows.find(r=>r.id==='tylor-c').possible,149.36);
const html=fs.readFileSync('weekly-updates.html','utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length);
assert.ok(html.includes('Week 3 Highlights') && html.includes('Week 2 recap archive') && html.includes('Week 1 recap archive'));
console.log('Week 3 checks passed: Swami 4-2 / season 8-4, 12 valid lineups, archives preserved, unique page IDs.');
